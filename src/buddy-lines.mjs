const turns = new Map();
const fill = (template, ctx) =>
  template
    .replace(/\{(\w+)\}/g, (_, key) => (ctx[key] == null || ctx[key] === "" ? "" : String(ctx[key])))
    .replace(/\s+([.,!?])/g, "$1")
    .replace(/\s{2,}/g, " ")
    .trim();

/** A line in the companion's own voice, rotating so it never repeats
 * back-to-back; falls back to the shared table. */
export function companionLine(companion, event, ctx = {}) {
  const list = LINES[companion]?.[event];
  if (!list?.length) return buddyLine(event, ctx);
  const key = `${companion}:${event}`;
  const turn = turns.get(key) ?? 0;
  turns.set(key, turn + 1);
  return fill(list[turn % list.length], ctx);
}
